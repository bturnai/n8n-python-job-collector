COMMON_MARK = "# ===== common.py (generated by scripts/sync.py; edit nodes/common.py) ====="
NODE_MARK = "# ===== {module}.py ====="
ENTRY_MARK = "# ===== entry ====="
INLINED = "# [inlined] "


def build(module):
    lines = []
    for line in (NODES_DIR / f"{module}.py").read_text().splitlines():
        if line.startswith("from common import"):
            if line.rstrip().endswith("("):
                raise SystemExit(f"{module}.py: keep the common import on one line")
            line = INLINED + line
        lines.append(line)
    return "\n".join([
        COMMON_MARK, (NODES_DIR / "common.py").read_text().rstrip(), "",
        NODE_MARK.format(module=module), "\n".join(lines).rstrip(), "",
        ENTRY_MARK, "return main(_items)", "",
    ])


def stdlib_allow():
    config = json.loads(RUNNER_CONFIG.read_text())
    python = next(r for r in config["task-runners"] if r["runner-type"] == "python")
    return python["env-overrides"]["N8N_RUNNERS_STDLIB_ALLOW"]


VALIDATOR = r"""
import json, sys
sys.path.insert(0, "/opt/runners/task-runner-python/.venv/lib/python3.13/site-packages")
from src.config.security_config import SecurityConfig
from src.constants import BUILTINS_DENY_DEFAULT
from src.task_analyzer import TaskAnalyzer
codes = json.load(sys.stdin)
analyzer = TaskAnalyzer(SecurityConfig(
    stdlib_allow=set(sys.argv[1].split(",")), external_allow=set(),
    builtins_deny=set(BUILTINS_DENY_DEFAULT.split(",")), runner_env_deny=True))
failed = 0
for name, code in codes.items():
    try:
        analyzer.validate(code)
        print("ok  ", name)
    except Exception as exc:
        failed += 1
        print("FAIL", name, "-", exc)
sys.exit(1 if failed else 0)
"""


# Builtins the runner removes at execution time (BUILTINS_DENY_DEFAULT). The
# sandbox's static analyzer does not flag them, so they are checked here.
DENIED_BUILTINS = {
    "eval", "exec", "compile", "open", "input", "breakpoint", "getattr", "object", "type",
    "vars", "setattr", "delattr", "hasattr", "dir", "memoryview", "globals", "locals",
    "license", "help", "credits", "copyright",
}


def runtime_violations(module, code):
    found = []
    for node in ast.walk(ast.parse(code)):
        if isinstance(node, ast.ClassDef):
            found.append(f"line {node.lineno}: class definitions fail at run time")
        elif isinstance(node, ast.Name) and node.id in DENIED_BUILTINS:
            found.append(f"line {node.lineno}: builtin '{node.id}' is removed in the sandbox")
    return [f"FAIL {module} - {msg}" for msg in found]


# Runs one node the way the runner does (task_executor._all_items): a fresh
# process, non-allow-listed modules dropped from sys.modules, guarded imports and
# filtered builtins. Catches what the static analyzer cannot, such as a standard
# library function importing a blocked module internally.
EXECUTOR = r"""
import json, sys
sys.path.insert(0, "/opt/runners/task-runner-python/.venv/lib/python3.13/site-packages")
from src.config.security_config import SecurityConfig
from src.constants import BUILTINS_DENY_DEFAULT, EXECUTOR_SAFE_FORMAT_KEY, EXECUTOR_USER_OUTPUT_KEY
from src.task_executor import TaskExecutor, _safe_format
payload = json.load(sys.stdin)
config = SecurityConfig(
    stdlib_allow=set(sys.argv[1].split(",")), external_allow=set(),
    builtins_deny=set(BUILTINS_DENY_DEFAULT.split(",")), runner_env_deny=True)
TaskExecutor._sanitize_sys_modules(config)
TaskExecutor._harden_importlib(config)
scope = {"__builtins__": TaskExecutor._filter_builtins(config), "_items": payload["items"],
         "_query": None, "print": print, EXECUTOR_SAFE_FORMAT_KEY: _safe_format}
try:
    exec(TaskExecutor._compile_user_code(payload["code"], "<node>"), scope)
    print(json.dumps({"ok": scope[EXECUTOR_USER_OUTPUT_KEY]}))
except BaseException as exc:
    print(json.dumps({"error": f"{type(exc).__name__}: {exc}"}))
"""

