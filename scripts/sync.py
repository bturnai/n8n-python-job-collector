"""Build the n8n Code-node source from `nodes/` and check it against the sandbox.

A Python Code node in n8n cannot import other files, so each node's code is
generated: `nodes/common.py`, then the node module (its `from common import`
line kept as a comment), then the entry call. Section markers show in the n8n
editor where each part comes from.

Usage:
  python scripts/sync.py build <module>    print the code of one node
  python scripts/sync.py check             validate every node in the runner sandbox,
                                           then run it there on a sample input
"""
import ast
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
NODES_DIR = ROOT / "nodes"
RUNNER_CONFIG = ROOT / "runner" / "n8n-task-runners.json"
CONTAINER = "n8n-runners"

# workflow id -> {node name in n8n: module in nodes/}
NODES = {
    "allasfigyelo0001": {
        "Keresesi URL-ek": "search_urls",
        "Uj allasok szurese": "filter_new",
        "Hirdetes-szoveg kinyerese": "extract_text",
        "Remote API URL-ek": "api_urls",
        "API talalatok feldolgozasa": "api_parse",
        "Duplikatumok kiszurese": "dedupe",
        "Riport osszeallitasa": "report",
    },
    "linkedinmail0001": {"Level kimentese": "linkedin_mail"},
    "kerelem0000001": {"Kerelem rogzitese": "request_click"},
    "valaszmail00001": {"Kerelem mentese": "request_reply"},
}

COMMON_MARK = "# ===== common.py (generated by scripts/sync.py; edit nodes/common.py) ====="
NODE_MARK = "# ===== {module}.py ====="
ENTRY_MARK = "# ===== entry ====="
INLINED = "# [inlined] "


def build(module):
    lines = []
    for line in (NODES_DIR / f"{module}.py").read_text().splitlines():
        if line.startswith("from common import"):
            if line.rstrip().endswith("("):
                raise SystemExit(f"{module}.py: keep the common import on one line")
            line = INLINED + line
        lines.append(line)
    return "\n".join([
        COMMON_MARK, (NODES_DIR / "common.py").read_text().rstrip(), "",
        NODE_MARK.format(module=module), "\n".join(lines).rstrip(), "",
        ENTRY_MARK, "return main(_items)", "",
    ])


def stdlib_allow():
    config = json.loads(RUNNER_CONFIG.read_text())
    python = next(r for r in config["task-runners"] if r["runner-type"] == "python")
    return python["env-overrides"]["N8N_RUNNERS_STDLIB_ALLOW"]


VALIDATOR = r"""
import json, sys
sys.path.insert(0, "/opt/runners/task-runner-python/.venv/lib/python3.13/site-packages")
from src.config.security_config import SecurityConfig
from src.constants import BUILTINS_DENY_DEFAULT
from src.task_analyzer import TaskAnalyzer
codes = json.load(sys.stdin)
analyzer = TaskAnalyzer(SecurityConfig(
    stdlib_allow=set(sys.argv[1].split(",")), external_allow=set(),
    builtins_deny=set(BUILTINS_DENY_DEFAULT.split(",")), runner_env_deny=True))
failed = 0
for name, code in codes.items():
    try:
        analyzer.validate(code)
        print("ok  ", name)
    except Exception as exc:
        failed += 1
        print("FAIL", name, "-", exc)
sys.exit(1 if failed else 0)
"""


# Builtins the runner removes at execution time (BUILTINS_DENY_DEFAULT). The
# sandbox's static analyzer does not flag them, so they are checked here.
DENIED_BUILTINS = {
    "eval", "exec", "compile", "open", "input", "breakpoint", "getattr", "object", "type",
    "vars", "setattr", "delattr", "hasattr", "dir", "memoryview", "globals", "locals",
    "license", "help", "credits", "copyright",
}


def runtime_violations(module, code):
    found = []
    for node in ast.walk(ast.parse(code)):
        if isinstance(node, ast.ClassDef):
            found.append(f"line {node.lineno}: class definitions fail at run time")
        elif isinstance(node, ast.Name) and node.id in DENIED_BUILTINS:
            found.append(f"line {node.lineno}: builtin '{node.id}' is removed in the sandbox")
    return [f"FAIL {module} - {msg}" for msg in found]


# Runs one node the way the runner does (task_executor._all_items): a fresh
# process, non-allow-listed modules dropped from sys.modules, guarded imports and
# filtered builtins. Catches what the static analyzer cannot, such as a standard
# library function importing a blocked module internally.
EXECUTOR = r"""
import json, sys
sys.path.insert(0, "/opt/runners/task-runner-python/.venv/lib/python3.13/site-packages")
from src.config.security_config import SecurityConfig
from src.constants import BUILTINS_DENY_DEFAULT, EXECUTOR_SAFE_FORMAT_KEY, EXECUTOR_USER_OUTPUT_KEY
from src.task_executor import TaskExecutor, _safe_format
payload = json.load(sys.stdin)
config = SecurityConfig(
    stdlib_allow=set(sys.argv[1].split(",")), external_allow=set(),
    builtins_deny=set(BUILTINS_DENY_DEFAULT.split(",")), runner_env_deny=True)
TaskExecutor._sanitize_sys_modules(config)
TaskExecutor._harden_importlib(config)
scope = {"__builtins__": TaskExecutor._filter_builtins(config), "_items": payload["items"],
         "_query": None, "print": print, EXECUTOR_SAFE_FORMAT_KEY: _safe_format}
try:
    exec(TaskExecutor._compile_user_code(payload["code"], "<node>"), scope)
    print(json.dumps({"ok": scope[EXECUTOR_USER_OUTPUT_KEY]}))
except BaseException as exc:
    print(json.dumps({"error": f"{type(exc).__name__}: {exc}"}))
"""

CARD = ('<li class="advertisement-result-list-item" data-prof-id="1" data-item-name="Data Analyst" '
        'data-affiliation="Acme" data-link="https://example.com/1">')
STATE = {"json": {"data": {"seenIds": ["0"], "seenKeys": []}}}
SAMPLES = {
    "search_urls": [],
    "filter_new": [STATE, {"json": {"placeLabel": "Tavmunka/Remote", "data": CARD}}],
    "extract_text": [{"json": {"id": "1", "data": "<p>Állás leírása: SQL</p>"}}],
    "api_urls": [],
    "api_parse": [STATE, {"json": {"forras": "remoteok", "data": json.dumps(
        [{}, {"id": 1, "position": "Data Scientist", "company": "Co", "url": "https://r/1"}])}}],
    "dedupe": [{"json": {"id": "1", "company": "A", "title": "Data Analyst"}}],
    "report": [STATE, {"json": {"id": "1", "company": "A", "title": "Data Analyst"}}],
    "linkedin_mail": [{"json": {"subject": "Állásajánlat 😀", "text": "x", "date": "2026-10-17",
                                "from": {"value": [{"address": "jobs@example.com"}]}}}],
    "request_click": [{"json": {"query": {"id": "123", "cim": "Data Analyst", "ceg": "Acme"}}}],
    "request_reply": [{"json": {"subject": "Re: x", "text": "Ezt kerem", "date": "2026-10-17"}}],
}


def run_in_sandbox(module, code):
    result = subprocess.run(
        ["docker", "exec", "-i", CONTAINER, "/opt/runners/task-runner-python/.venv/bin/python",
         "-c", EXECUTOR, stdlib_allow()],
        input=json.dumps({"code": code, "items": SAMPLES[module]}), capture_output=True, text=True,
    )
    lines = result.stdout.strip().splitlines()
    if not lines:
        return f"no output ({result.stderr.strip()[-300:]})"
    outcome = json.loads(lines[-1])
    if "error" in outcome:
        return outcome["error"]
    if not isinstance(outcome["ok"], list) or not outcome["ok"]:
        return f"unexpected result: {outcome['ok']!r}"
    return None


def check(modules=None):
    modules = modules or sorted({m for nodes in NODES.values() for m in nodes.values()})
    codes = {module: build(module) for module in modules}
    local = [line for module, code in codes.items() for line in runtime_violations(module, code)]
    if local:
        print("\n".join(local))
        return 1
    result = subprocess.run(
        ["docker", "exec", "-i", CONTAINER, "/opt/runners/task-runner-python/.venv/bin/python",
         "-c", VALIDATOR, stdlib_allow()],
        input=json.dumps(codes), capture_output=True, text=True,
    )
    sys.stdout.write(result.stdout + result.stderr)
    if result.returncode:
        return result.returncode

    failed = 0
    for module, code in codes.items():
        error = run_in_sandbox(module, code)
        print(("FAIL " if error else "run  ") + module + (f" - {error}" if error else ""))
        failed += bool(error)
    return 1 if failed else 0


def main(argv):
    if len(argv) >= 2 and argv[0] == "build":
        sys.stdout.write(build(argv[1]))
        return 0
    if argv and argv[0] == "check":
        return check(argv[1:] or None)
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
